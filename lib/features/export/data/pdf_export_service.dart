import 'dart:typed_data';

import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:intl/intl.dart';
import 'package:loan_manager/core/database/app_database.dart';
import 'package:loan_manager/core/database/app_database_provider.dart';
import 'package:loan_manager/core/utils/jalali_utils.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import 'export_data.dart';

final pdfExportServiceProvider = Provider<PdfExportService>(
  (ref) => PdfExportService(ref.read(appDatabaseProvider)),
);

final NumberFormat _money = NumberFormat.decimalPattern('en');

/// Builds a Persian RTL PDF report for the selected loans and shares the
/// generated bytes through the platform share sheet.
class PdfExportService {
  PdfExportService(this._db);

  final AppDatabase _db;

  static const String _regularAsset = 'assets/fonts/IRANSansX-Regular.ttf';
  static const String _boldAsset = 'assets/fonts/IRANSansX-Bold.ttf';
  static const pw.Color _ink = pw.Color(0xFF212121);
  static const pw.Color _muted = pw.Color(0xFF757575);
  static const pw.Color _accent = pw.Color(0xFF1565C0);
  static const pw.Color _line = pw.Color(0xFFE0E0E0);

  Future<bool> share({required List<String> loanIds, DateRangeFilter? range}) async {
    final bytes = await build(loanIds: loanIds, range: range);
    return Printing.sharePdf(bytes: bytes, filename: 'loan_report.pdf');
  }

  Future<Uint8List> build({required List<String> loanIds, DateRangeFilter? range}) async {
    final regular = pw.Font.ttf(await rootBundle.load(_regularAsset));
    final bold = pw.Font.ttf(await rootBundle.load(_boldAsset));

    final data = await ExportDataLoader(_db).load(loanIds: loanIds, range: range);
    if (data.isEmpty) {
      throw const ExportException('هیچ وامی برای خروجی‌گیری انتخاب نشده است');
    }

    final names = {for (final l in data.loans) l.id: l.name};
    final banks = {for (final l in data.loans) l.id: l.bankName ?? ''};
    final remaining = data.installments.fold<int>(
      0,
      (sum, i) => sum + (i.amount - i.paidAmount - i.waivedAmount).clamp(0, i.amount),
    );

    final doc = pw.Document();
    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        textDirection: pw.TextDirection.rtl,
        margin: const pw.EdgeInsets.all(28),
        header: (context) => _header(context, regular, bold, range),
        footer: (context) => _footer(context, regular),
        build: (context) => [
          pw.Text(
            'وام: ${data.loans.length}    قسط: ${data.installments.length}    پرداخت: ${data.payments.length}',
            style: pw.TextStyle(font: regular, fontSize: 10, color: _muted),
          ),
          pw.SizedBox(height: 8),
          pw.Table(
            border: pw.TableBorder.all(color: _line, width: 0.5),
            columnWidths: const [
              pw.FixedColumnWidth(90),
              pw.FixedColumnWidth(60),
              pw.FixedColumnWidth(28),
              pw.FixedColumnWidth(68),
              pw.FixedColumnWidth(78),
              pw.FixedColumnWidth(78),
              pw.FixedColumnWidth(78),
              pw.FixedColumnWidth(42),
            ],
            header: pw.TableRow(
              decoration: pw.BoxDecoration(color: _accent),
              children: [
                _headerCell('نام وام', bold),
                _headerCell('بانک', bold),
                _headerCell('قسط', bold),
                _headerCell('سررسید', bold),
                _headerCell('مبلغ', bold),
                _headerCell('پرداخت‌شده', bold),
                _headerCell('باقی‌مانده', bold),
                _headerCell('وضعیت', bold),
              ],
            ),
            children: [
              for (final i in data.installments)
                pw.TableRow(
                  children: [
                    _cell(names[i.loanId] ?? i.loanId, regular),
                    _cell(banks[i.loanId] ?? '', regular),
                    _cell('${i.sequenceNumber}', regular),
                    _cell(JalaliUtils.formatJalali(i.dueDate), regular),
                    _cell(_money.format(i.amount), regular),
                    _cell(_money.format(i.paidAmount), regular),
                    _cell(_money.format((i.amount - i.paidAmount - i.waivedAmount).clamp(0, i.amount)), regular),
                    _cell(_status(i), regular),
                  ],
                ),
            ],
          ),
          pw.SizedBox(height: 12),
          pw.Text('مجموع باقی‌مانده: ${_money.format(remaining)} تومان',
              style: pw.TextStyle(font: bold, fontSize: 12, color: _accent)),
        ],
      ),
    );

    return doc.save();
  }

  String _status(InstallmentRow i) {
    if (i.amount - i.paidAmount - i.waivedAmount <= 0) return 'تسویه شد';
    final due = DateTime.tryParse(i.dueDate);
    if (due != null && due.isBefore(DateTime.now())) return 'معوق';
    return 'باقی‌مانده';
  }

  pw.Widget _header(pw.PageContext context, pw.Font regular, pw.Font bold, DateRangeFilter? range) {
    final String title;
    if (range == null || range.isEmpty) {
      title = 'گزارش وام‌ها';
    } else {
      title = 'گزارش وام‌ها (${JalaliUtils.formatFromDateTime(range.from!)} تا ${JalaliUtils.formatFromDateTime(range.to!)})';
    }
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(title, style: pw.TextStyle(font: bold, fontSize: 18, color: _accent)),
        pw.SizedBox(height: 4),
        pw.Text(
          'تاریخ صدور: ${JalaliUtils.formatFromDateTime(DateTime.now())}',
          style: pw.TextStyle(font: regular, fontSize: 10, color: _muted),
        ),
      ],
    );
  }

  pw.Widget _footer(pw.PageContext context, pw.Font regular) {
    return pw.Container(
      alignment: pw.Alignment.center,
      padding: const pw.EdgeInsets.only(top: 8),
      child: pw.Text(
        'صفحه ${context.pageNumber} از ${context.pagesCount}',
        style: pw.TextStyle(font: regular, fontSize: 9, color: _muted),
      ),
    );
  }

  pw.Widget _headerCell(String text, pw.Font bold) => pw.Container(
        padding: const pw.EdgeInsets.symmetric(vertical: 6, horizontal: 8),
        alignment: pw.Alignment.center,
        child: pw.Text(text, style: pw.TextStyle(font: bold, fontSize: 9, color: pw.Color(0xFFFFFFFF))),
      );

  pw.Widget _cell(String text, pw.Font regular, {pw.Alignment align = pw.Alignment.centerRight}) => pw.Container(
        padding: const pw.EdgeInsets.symmetric(vertical: 5, horizontal: 8),
        alignment: align,
        child: pw.Text(text, style: pw.TextStyle(font: regular, fontSize: 8.5, color: _ink)),
      );
}
